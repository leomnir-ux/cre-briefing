// Reads every briefing in briefings/ and writes briefings-data.js for the website.
// Run with: node build.js
// The briefing files are only read, never changed.

const fs = require("fs");
const path = require("path");

const briefingsDir = path.join(__dirname, "briefings");
const outFile = path.join(__dirname, "briefings-data.js");

// Button names, in the order they appear. A heading matches a button when it
// starts with that name, so "Other (Senior Housing, ...)" becomes "Other".
const SECTION_NAMES = [
  "Market Summary",
  "Capital Markets",
  "Office",
  "Retail",
  "Industrial",
  "Multifamily",
  "Hospitality",
  "Data Centers",
  "Other",
];

function parseBriefing(file) {
  const date = file.replace(/\.md$/, "");
  const text = fs.readFileSync(path.join(briefingsDir, file), "utf8").replace(/\r\n/g, "\n");

  const titleMatch = text.match(/^# (.+)$/m);
  const title = titleMatch ? titleMatch[1].trim() : date;

  // Split on "## " headings. "### " story headings stay inside their section.
  const sections = {};
  const parts = text.split(/^## (?=\S)/m).slice(1);
  for (const part of parts) {
    const newline = part.indexOf("\n");
    const heading = part.slice(0, newline).trim();
    const body = part.slice(newline + 1).trim();
    const name = SECTION_NAMES.find((n) => heading.startsWith(n));
    if (!name) {
      console.warn(`  Warning: ${file} has an unrecognized heading "${heading}". Skipped.`);
      continue;
    }
    sections[name] = body;
  }

  const missing = SECTION_NAMES.filter((n) => !(n in sections));
  if (missing.length) {
    console.warn(`  Warning: ${file} is missing sections: ${missing.join(", ")}`);
  }

  return { date, title, sections };
}

const files = fs
  .readdirSync(briefingsDir)
  .filter((f) => /^\d{4}-\d{2}-\d{2}\.md$/.test(f))
  .sort()
  .reverse(); // newest first

const briefings = files.map(parseBriefing);

const output =
  "// Generated by build.js. Do not edit by hand.\n" +
  "window.SECTION_NAMES = " + JSON.stringify(SECTION_NAMES) + ";\n" +
  "window.BRIEFINGS = " + JSON.stringify(briefings, null, 1) + ";\n";

fs.writeFileSync(outFile, output);

console.log(`Wrote briefings-data.js with ${briefings.length} briefing(s):`);
for (const b of briefings) {
  console.log(`  ${b.date}: ${Object.keys(b.sections).length} sections`);
}
